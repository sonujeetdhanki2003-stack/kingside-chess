
import asyncio,sys,time
from playwright.async_api import async_playwright
UA="Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Mobile Safari/537.36"
BASE=sys.argv[1].rstrip('/')
errs=[]; ok=[]
def check(name,cond):
    ok.append((name,bool(cond))); print(('PASS ' if cond else 'FAIL ')+name, flush=True)
async def click_sq(p,sq):
    b=await p.locator(f'.sq[data-square="{sq}"]').bounding_box(); await p.mouse.click(b['x']+b['width']/2,b['y']+b['height']/2)
async def main():
  async with async_playwright() as pw:
    br=await pw.chromium.launch()
    c=await br.new_context(viewport={'width':360,'height':740},device_scale_factor=2,is_mobile=True,has_touch=True,user_agent=UA)
    p=await c.new_page(); p.on('pageerror',lambda e: errs.append(str(e)))
    await p.goto(BASE+'/'); await p.wait_for_timeout(1200)
    cls=lambda: p.evaluate('document.body.className')
    check('opens on home hub, no sheet', 'view-home' in await cls() and await p.locator('#sheet-new').is_hidden())
    check('tab bar visible on home', await p.locator('#tabbar').is_visible())
    check('home tab active', await p.locator('[data-tab="home"].on').count()==1)
    # no horizontal overflow
    check('no sideways scroll (home)', await p.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    # Play tab with no game -> board + computer sheet
    await p.click('[data-tab="play"]'); await p.wait_for_timeout(300)
    check('Play tab opens the board', 'view-game' in await cls())
    check('Play tab offers the computer sheet', await p.locator('#sheet-new').is_visible() and (await p.inner_text('#new-title'))=='Play Computer')
    check('tab bar hidden in game', await p.locator('#tabbar').is_hidden())
    await p.click('#new-start'); await p.wait_for_timeout(500)
    await p.wait_for_function('!window.__chess.thinking && window.__chess.chess.turn()===window.__chess.settings.color',timeout=20000)
    mv = 'e2e4' if await p.evaluate('window.__chess.settings.color')=='w' else 'e7e5'
    await click_sq(p,mv[:2]); await click_sq(p,mv[2:]); await p.wait_for_timeout(500)
    check('move played', await p.evaluate('window.__chess.chess.history().length')>=1)
    check('no sideways scroll (game)', await p.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    check('toolbar docked & visible', await p.locator('#btn-flip').is_visible() and await p.locator('#btn-resign').is_visible())
    # browser back -> home, with continue card
    await p.go_back(); await p.wait_for_timeout(500)
    check('browser back goes home', 'view-home' in await cls())
    check('continue card shown', await p.locator('#hub-continue').is_visible())
    await p.click('#hub-continue'); await p.wait_for_timeout(300)
    check('continue returns to the same game', 'view-game' in await cls() and await p.evaluate('window.__chess.chess.history().length')>=1)
    await p.click('#btn-home'); await p.wait_for_timeout(500)
    check('home button goes home', 'view-home' in await cls())
    # More sheet rows
    await p.click('[data-tab="more"]'); await p.wait_for_timeout(200)
    check('More sheet open', await p.locator('#sheet-more').is_visible())
    snd=await p.evaluate('JSON.parse(localStorage.getItem("kingside-chess-prefs-v1")||"{}").sound')
    await p.click('[data-more="sound"]'); await p.wait_for_timeout(100)
    snd2=await p.evaluate('JSON.parse(localStorage.getItem("kingside-chess-prefs-v1")||"{}").sound')
    check('sound toggle works from More', snd!=snd2)
    await p.click('[data-more="sound"]')
    await p.click('[data-more="settings"]'); await p.wait_for_timeout(200)
    check('settings opens from More', await p.locator('#sheet-settings').is_visible())
    await p.click('#settings-done')
    await p.click('[data-tab="more"]'); await p.click('[data-more="pvp"]'); await p.wait_for_timeout(200)
    check('2 Players sheet', (await p.inner_text('#new-title'))=='2 Players')
    await p.click('#new-start'); await p.wait_for_timeout(400)
    check('2-player game starts', await p.evaluate('window.__chess.settings.mode')=='pvp' and 'view-game' in await cls())
    await click_sq(p,'e2'); await click_sq(p,'e4'); await click_sq(p,'e7'); await click_sq(p,'e5'); await p.wait_for_timeout(300)
    check('2-player moves both sides', await p.evaluate('window.__chess.chess.history().length')==2)
    await p.click('#btn-home'); await p.wait_for_timeout(400)
    await p.click('[data-tab="more"]'); await p.click('[data-more="join"]'); await p.wait_for_timeout(300)
    check('join-by-code box shown', await p.locator('#join-code').is_visible())
    await p.fill('#join-code','ZZZZZZ'); await p.click('#join-go'); await p.wait_for_timeout(1200)
    check('bad code gives a message', 'No game found' in (await p.inner_text('#toast')))
    await p.click('#new-cancel')
    await p.click('[data-tab="more"]'); await p.click('[data-more="leaders"]'); await p.wait_for_timeout(800)
    check('leaderboard opens', await p.locator('#tscreen').is_visible())
    check('tab bar stays on tournaments screen', await p.locator('#tabbar').is_visible())
    await p.click('[data-tab="puzzles"]'); await p.wait_for_timeout(800)
    check('puzzles tab switches screens', await p.locator('#pscreen').is_visible() and await p.locator('#tscreen').is_hidden())
    check('puzzles tab active', await p.locator('[data-tab="puzzles"].on').count()==1)
    await p.click('[data-tab="friends"]'); await p.wait_for_timeout(500)
    check('friends tab opens friends', (await p.inner_text('#a-title'))=='Friends' and await p.locator('[data-tab="friends"].on').count()==1)
    await p.click('[data-tab="home"]'); await p.wait_for_timeout(300)
    check('home tab closes overlays', await p.locator('#ascreen').is_hidden() and 'view-home' in await cls())
    await p.click('#btn-hub-review'); await p.wait_for_timeout(800)
    check('review tile opens review of the last game', await p.locator('#rscreen').is_visible())
    await p.click('#r-back'); await p.wait_for_timeout(500)
    await p.click('#hub-hello'); await p.wait_for_timeout(400)
    check('profile card opens sign-in', await p.locator('#ascreen').is_visible())
    print('ERRS',errs); print('SUMMARY', sum(1 for _,v in ok if v),'/',len(ok))
    await br.close()
asyncio.run(main())
